// Copies the real Helicon UI (packages/ui/src) and its tokens (apps/web/src/theme.css) into the
// landing page, so the demos render the exact product components. Re-run after product UI changes:
//   node scripts/sync-product-ui.mjs
import { cpSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const from = join(root, "../packages/ui/src");
const to = join(root, "src/product");

rmSync(to, { recursive: true, force: true });
cpSync(from, to, { recursive: true });

const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      walk(path);
      continue;
    }
    if (!/\.tsx?$/.test(name)) continue;
    const src = readFileSync(path, "utf8");
    // NodeNext `.js` specifiers become extensionless for the Next.js bundler.
    let out = src.replace(/(from\s+|import\(\s*)(["'])(\.\.?\/[^"']+)\.js\2/g, "$1$2$3$2");
    // Radix portals mount inside the demo window instead of document.body.
    if (/<\w+\.Portal>/.test(out)) {
      out = out.replace(/<(\w+)\.Portal>/g, "<$1.Portal container={usePortalContainer()}>");
      out = `import { usePortalContainer } from "@/demo/portal";\n${out}`;
    }
    // Inside a demo, dialogs stay non-modal so they never lock or hide the landing page around them.
    out = out.replace(/<RDialog\.Root open=\{props\.open\} onOpenChange=\{props\.onOpenChange\}>/g, "<RDialog.Root open={props.open} onOpenChange={props.onOpenChange} modal={!usePortalContainer()}>");
    // A demo's composer only grabs focus once the visitor is already working inside that demo.
    if (out.includes("if (props.autoFocus && !props.readOnly && el) {")) {
      out = out.replace("if (props.autoFocus && !props.readOnly && el) {", "if (props.autoFocus && !props.readOnly && el && mayAutoFocus(el)) {");
      out = `import { mayAutoFocus } from "@/demo/portal";\n${out}`;
    }
    // React 19 reads inert as a boolean; the product's React 18 spelling ("") would leave it off.
    out = out.replace('({ inert: "" } as Record<string, string>)', "({ inert: true } as Record<string, boolean>)");
    if (out !== src) writeFileSync(path, out);
  }
};
walk(to);

// Product tokens, minus the shell's global page rules and font files (the landing loads its own).
let css = readFileSync(join(root, "../apps/web/src/theme.css"), "utf8");
css = css
  .replace(/^@import .*\n/gm, "")
  .replace(/^@source .*\n/gm, "")
  .replace(/^@custom-variant dark .*\n/m, "")
  .replace(/^\s*--font-sans:.*\n/m, "")
  .replace(/^(\s*--font-mono:).*\n/m, '$1 var(--font-jetbrains), ui-monospace, "Cascadia Code", Consolas, monospace;\n')
  .replace(/^(\s*--font-display:).*\n/m, '$1 var(--font-newsreader), "Iowan Old Style", Georgia, serif;\n');
const baseStart = css.indexOf("@layer base {");
const baseEnd = css.indexOf("@layer components {");
if (baseStart < 0 || baseEnd < 0) throw new Error("theme.css layout changed; update the sync script");
css = css.slice(0, baseStart) + css.slice(baseEnd);
writeFileSync(
  join(root, "src/app/product-theme.css"),
  `/* GENERATED by scripts/sync-product-ui.mjs from apps/web/src/theme.css. Do not edit. */\n${css}`,
);
console.log("synced product UI into src/product and tokens into src/app/product-theme.css");
